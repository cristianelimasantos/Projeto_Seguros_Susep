USE SUSEP_CASCO

-- 1. Verificação de dados nulos
SELECT
    SUM(CASE WHEN cod_categoria IS NULL THEN 1 ELSE 0 END) AS nulos_categoria,
    SUM(CASE WHEN cod_regiao   IS NULL THEN 1 ELSE 0 END) AS nulos_regiao,
    SUM(CASE WHEN premio1      IS NULL THEN 1 ELSE 0 END) AS nulos_premio,
    SUM(CASE WHEN indeniz1     IS NULL THEN 1 ELSE 0 END) AS nulos_indeniz1,
    COUNT(*) AS total_linhas
FROM fato_casco;


-- 2. Verificação dos códigos das Dimensões vs. Tabela fato

-- dim Categoria
SELECT 
	DISTINCT C.cod_categoria,
	CT.categoria AS Nome
FROM fato_casco C LEFT JOIN dim_categoria CT
ON C.cod_categoria = CT.codigo
ORDER BY C.cod_categoria;

-- dim Idade
SELECT
	DISTINCT C.cod_idade,
	I.descricao AS Descricao
FROM fato_casco C LEFT JOIN dim_idade I
ON C.cod_idade = I.codigo
ORDER BY C.cod_idade;


-- dim Regiao
SELECT
	DISTINCT C.cod_regiao,
	R.descricao AS Descricao
FROM fato_casco C LEFT JOIN dim_regiao R
ON C.cod_regiao = R.codigo
ORDER BY R.descricao


-- dim Sexo
SELECT
	DISTINCT C.cod_sexo,
	S.descricao AS Descricao
FROM fato_casco C LEFT JOIN dim_sexo S
ON C.cod_sexo = S.codigo
ORDER BY C.cod_sexo


-- dim Veículo
SELECT
	DISTINCT C.cod_modelo,
	V.descricao AS Descricao
FROM fato_casco C LEFT JOIN dim_veiculo V
ON C.cod_modelo = V.codigo
ORDER BY V.descricao


